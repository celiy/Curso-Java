package DataTypes;

public class Primitives {
    // Integer types
    byte byteVar = 127;          // 8 bits: -128 to 127
    short shortVar = 32767;      // 16 bits: -32768 to 32767
    int intVar = 123;            // 32 bits: -2147483648 to 2147483647
    long longVar = 123L;         // 64 bits: needs L suffix

    // Floating-point types
    float floatVar = 3.14f;      // 32 bits: needs f suffix
    double doubleVar = 3.14;     // 64 bits

    // Character (16-bit Unicode)
    char charVar = 'A';          // 'A' or 65

    // Boolean
    boolean booleanVar = true;   // true or false
}
